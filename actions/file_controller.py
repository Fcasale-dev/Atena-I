# Undo keeps a file's previous contents in memory so `write` can be reversed.
# Above this size it does not — a 200 MB log would sit in RAM for the rest of
# the session to protect an edit nobody is going to take back.
_UNDO_CONTENT_LIMIT = 1_000_000


def _undo_move(src: Path, dst: Path):
    """Reverse of a move: put it back where it came from."""
    def _fn():
        if not dst.exists():
            return f"'{dst.name}' is no longer there — nothing moved back."
        src.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(dst), str(src))
        return f"'{src.name}' is back in {src.parent.name}/."
    return _fn


def _undo_create(target: Path):
    """Reverse of a create: remove what we made — and only if we still made it.

    Deliberately refuses to touch a directory that has since been filled: the
    undo for 'create a folder' is not 'delete whatever ended up in it'."""
    def _fn():
        if not target.exists():
            return f"'{target.name}' is already gone."
        if target.is_dir():
            if any(target.iterdir()):
                return (f"'{target.name}' is not empty any more — "
                        f"leaving it alone rather than deleting your files.")
            target.rmdir()
        else:
            target.unlink()
        return f"Removed '{target.name}'."
    return _fn


def _undo_write(target: Path, previous: str | None):
    """Reverse of a write: restore the old contents, or remove a file that did
    not exist before the write created it."""
    def _fn():
        if previous is None:
            if target.exists():
                target.unlink()
                return f"Removed '{target.name}' — it did not exist before."
            return f"'{target.name}' is already gone."
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(previous, encoding="utf-8")
        return f"Restored the previous contents of '{target.name}'."
    return _fn


def _restore_from_trash(original: Path) -> str:
    """Best-effort undelete.

    delete_file uses send2trash, which is the right call: the file lands in the
    Recycle Bin / Trash where the person can also find it themselves. Getting it
    back out again is shell work and only reliable on Windows, where pywin32 is
    already a dependency. Everywhere else this says where the file is instead of
    pretending it failed — the file is not lost either way."""
    if _OS == "Windows":
        try:
            import win32com.client
            shell = win32com.client.Dispatch("Shell.Application")
            bin_folder = shell.NameSpace(10)      # ssfBITBUCKET
            for item in bin_folder.Items():
                if str(bin_folder.GetDetailsOf(item, 1)).strip().lower() == \
                        str(original.parent).strip().lower():
                    if str(item.Name).strip().lower() == original.name.strip().lower():
                        item.InvokeVerb("UNDELETE")
                        return f"'{original.name}' restored from the Recycle Bin."
        except Exception as e:
            print(f"[file] Recycle Bin restore failed: {e}")
    return (f"'{original.name}' is in the Recycle Bin — I could not pull it back "
            f"automatically, but it is there and can be restored by hand.")


def _other_drives() -> list[Path]:
    """Every drive except the system one (D:, E:, ...). On C: only the user's
    home is allowed, so Windows / Program Files stay out of reach."""
    if _OS != "Windows":
        return []
    sysdrive = (os.environ.get("SystemDrive", "C:") or "C:").upper().rstrip("\\")
    out = []
    for letter in "ABCDEFGHIJKLMNOPQRSTUVWXYZ":
        d = f"{letter}:"
        if d == sysdrive:
            continue
        p = Path(d + "\\")
        try:
            if p.exists():
                out.append(p)
        except Exception:
            pass
    return out


def _extra_roots() -> list[Path]:
    """Extra folders the user allowed in config/api_keys.json → "file_roots"."""
    try:
        from memory.config_manager import load_api_keys
        return [Path(p) for p in (load_api_keys().get("file_roots") or []) if p]
    except Exception:
        return []


def _safe_roots() -> list[Path]:
    return [Path.home()] + _other_drives() + _extra_roots()


_SAFE_ROOTS: list[Path] = [Path.home()]   # kept for compatibility


def _is_safe_path(target: Path) -> bool:
    """Is the given path inside an allowed root? If not, reject the operation."""
    try:
        resolved = target.resolve()
        return any(
            resolved == root.resolve() or resolved.is_relative_to(root.resolve())
            for root in _safe_roots()
        )
    except Exception:
        return False


# ── Folder index ────────────────────────────────────────────────────────────
# Spoken folder names ("abre a pasta Provas no disco D") are looked up in an
# in-memory index of every folder in the allowed roots. It is built in a
# background thread at startup and refreshed every few minutes, so a lookup is
# instant instead of crawling the disk while the user waits.
import threading as _threading
import time as _time
import unicodedata as _ud
import re as _re_idx

_SKIP_DIRS = {"appdata", "$recycle.bin", "system volume information", "node_modules",
              ".git", "windows", "program files", "program files (x86)", "programdata",
              "__pycache__", "site-packages", ".venv", "venv", "$windows.~bt",
              "windowsapps", "msocache", "recovery", "config.msi"}
_INDEX_MAX_DEPTH = 8
_INDEX_MAX_ENTRIES = 500_000
_INDEX_REFRESH_S = 15 * 60

_index: dict[str, list[str]] = {}
_index_ready = False
_index_lock = _threading.Lock()


def _key(name: str) -> str:
    """Normalise for matching: no accents, no case, letters/digits only."""
    n = _ud.normalize("NFKD", name or "")
    n = "".join(c for c in n if not _ud.combining(c))
    return _re_idx.sub(r"[^a-z0-9]", "", n.lower())


def _build_index() -> None:
    global _index, _index_ready
    idx: dict[str, list[str]] = {}
    count = 0
    stack = [(str(r), 0) for r in _safe_roots()]
    while stack and count < _INDEX_MAX_ENTRIES:
        d, depth = stack.pop()
        try:
            with os.scandir(d) as it:
                for e in it:
                    try:
                        if not e.is_dir(follow_symlinks=False):
                            continue
                    except OSError:
                        continue
                    low = e.name.lower()
                    if low in _SKIP_DIRS or e.name.startswith("."):
                        continue
                    idx.setdefault(_key(e.name), []).append(e.path)
                    count += 1
                    if depth + 1 < _INDEX_MAX_DEPTH:
                        stack.append((e.path, depth + 1))
        except OSError:
            continue
    with _index_lock:
        _index = idx
        _index_ready = True
    print(f"[file] Índice de pastas pronto: {count} pastas.")


def _index_loop() -> None:
    while True:
        try:
            _build_index()
        except Exception as e:
            print(f"[file] index error: {e}")
        _time.sleep(_INDEX_REFRESH_S)


_threading.Thread(target=_index_loop, daemon=True, name="FolderIndex").start()


def _index_add(path: Path) -> None:
    with _index_lock:
        _index.setdefault(_key(path.name), []).append(str(path))


def _is_under(child: str, parent: Path | None) -> bool:
    if parent is None:
        return True
    try:
        return Path(child).resolve().is_relative_to(parent.resolve())
    except Exception:
        return False


def _live_search(want: str, within: list[Path], max_depth: int = 5) -> Path | None:
    level = list(within)
    for _ in range(max_depth):
        nxt = []
        for d in level:
            try:
                for c in d.iterdir():
                    try:
                        if not c.is_dir() or c.name.lower() in _SKIP_DIRS or c.name.startswith("."):
                            continue
                    except Exception:
                        continue
                    if _key(c.name) == want:
                        return c
                    nxt.append(c)
            except Exception:
                continue
        level = nxt
        if len(level) > 20000:
            break
    return None


def _find_dir_by_name(name: str, within: Path | None = None) -> Path | None:
    """Find a folder by its (spoken) name, optionally only inside `within`.
    Exact name first, then names that contain it; shallowest path wins."""
    want = _key(name)
    if not want:
        return None
    with _index_lock:
        exact = [p for p in _index.get(want, []) if _is_under(p, within)]
        if not exact:
            # partial: "mark lv" → "Mark-LV-main"
            exact = [p for k, ps in _index.items() if want in k
                     for p in ps if _is_under(p, within)][:200]
    hits = [p for p in exact if os.path.isdir(p)]
    if hits:
        hits.sort(key=lambda p: (p.count(os.sep), len(p)))
        return Path(hits[0])
    # not indexed yet (or created a moment ago): quick live crawl
    roots = [within] if within is not None else _safe_roots()
    return _live_search(want, roots)


def _locate(parts: list[str], root: Path | None) -> Path | None:
    """Walk 'Projetos/Faculdade/Provas': each part is taken literally if it
    exists under the current folder, otherwise searched for inside it."""
    cur = root
    for part in parts:
        if cur is not None and (cur / part).exists():
            cur = cur / part
            continue
        found = _find_dir_by_name(part, within=cur)
        if found is None:
            return None
        cur = found
    return cur

